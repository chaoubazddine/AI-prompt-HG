/**
 * Clean and normalize Arabic string for comparison
 */
function normalizeArabicString(str: string): string {
  if (!str) return '';
  return str
    .replace(/[َُِّْـ]/g, '')
    .replace(/[أإآء]/g, 'ا')
    .replace(/ة/g, 'ه')
    .replace(/ى/g, 'ي')
    .replace(/[\(\)\[\]،:\-\/]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/**
 * Find exact or best matching official curriculum sections blueprint for a given lesson
 */
export function getOfficialCurriculumSections(
  lessonTitle: string,
  level?: string,
  component?: string
): LessonCurriculumBlueprint | null {
  if (!lessonTitle) return null;

  const normalizedInput = normalizeArabicString(lessonTitle);

  // 1. Exact match on title
  const exact = OFFICIAL_CURRICULUM_SECTIONS.find(item => {
    const normTitle = normalizeArabicString(item.lessonTitle);
    return normTitle === normalizedInput;
  });
  if (exact) return exact;

  // 2. Partial containment match
  const partial = OFFICIAL_CURRICULUM_SECTIONS.find(item => {
    const normTitle = normalizeArabicString(item.lessonTitle);
    return normalizedInput.includes(normTitle) || normTitle.includes(normalizedInput);
  });
  if (partial) return partial;

  // 3. Keyword matching
  const stopWords = new Set(['درس', 'موضوع', 'في', 'من', 'عن', 'على', 'الى', 'إلى', 'مع', 'بين', 'حول', 'ان', 'أن', 'لا', 'ما', 'هو', 'هي']);
  const keywords = normalizedInput.split(/\s+/).filter(w => w.length >= 3 && !stopWords.has(w));

  let bestMatch: LessonCurriculumBlueprint | null = null;
  let highestScore = 0;

  for (const item of OFFICIAL_CURRICULUM_SECTIONS) {
    const itemNorm = normalizeArabicString(item.lessonTitle);
    let score = 0;
    for (const kw of keywords) {
      if (itemNorm.includes(kw)) score += 2;
    }
    if (component && item.component === component) score += 1;
    if (level && item.level.includes(level)) score += 1;

    if (score > highestScore && score >= 2) {
      highestScore = score;
      bestMatch = item;
    }
  }

  return bestMatch;
}
