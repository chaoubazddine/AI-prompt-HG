/**
 * Get all available textbooks for a specific school level.
 * Lists all official approved textbooks in Morocco, including the comparative synthesis option.
 */
export function getTextbooksForLevel(level: string): string[] {
  const norm = normalizeString(level);
  if (norm.includes('الثالثه')) {
    return [
      'التجديد في الاجتماعيات',
      'منار الاجتماعيات',
      'توليف رسمي بين مقررات المستوى (مقارنة متقاطعة)'
    ];
  }
  if (norm.includes('الاولي') && norm.includes('اعدادي')) {
    return [
      'في رحاب الاجتماعيات',
      'فضاء الاجتماعيات',
      'منار الاجتماعيات',
      'توليف رسمي بين مقررات المستوى (مقارنة متقاطعة)'
    ];
  }
  if (norm.includes('الثانيه') && norm.includes('اعدادي')) {
    return [
      'النجاح في الاجتماعيات',
      'فضاء الاجتماعيات',
      'المفيد في الاجتماعيات',
      'توليف رسمي بين مقررات المستوى (مقارنة متقاطعة)'
    ];
  }
  if (norm.includes('جذع') || norm.includes('مشترك')) {
    return [
      'المنار في التاريخ والجغرافيا',
      'في رحاب التاريخ والجغرافيا',
      'مورد الاجتماعيات',
      'توليف رسمي بين مقررات المستوى (مقارنة متقاطعة)'
    ];
  }
  if (norm.includes('باك') || norm.includes('بكالوريا')) {
    return [
      'المنار في التاريخ والجغرافيا',
      'في رحاب التاريخ والجغرافيا',
      'المسار في الاجتماعيات',
      'توليف رسمي بين مقررات المستوى (مقارنة متقاطعة)'
    ];
  }
  return [
    'التجديد في الاجتماعيات',
    'منار الاجتماعيات',
    'في رحاب الاجتماعيات',
    'توليف رسمي بين مقررات المستوى (مقارنة متقاطعة)'
  ];
}
