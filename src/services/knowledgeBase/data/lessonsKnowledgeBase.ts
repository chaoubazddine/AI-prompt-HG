/**
 * Normalizes Arabic text for flexible matching (removes diacritics, unifies alifs, numbers, etc.)
 */
function normalizeArabic(text: string): string {
  return text
    .replace(/[\u064B-\u065F\u0670]/g, '') // Remove tashkeel / diacritics
    .replace(/[إأآٱ]/g, 'ا') // Normalize alif
    .replace(/ة/g, 'ه') // Normalize taa marbuta
    .replace(/ى/g, 'ي') // Normalize alif maqsoora
    .replace(/اوروبيه/g, 'اوربيه') // Normalize European spelling variation
    .replace(/التاسع\s*عشر/g, '19') // Normalize 19th century representation
    .replace(/العشرين/g, '20')
    .replace(/19\s*م/g, '19')
    .replace(/20\s*م/g, '20')
    .replace(/[^\u0600-\u06FFa-zA-Z0-9\s]/g, ' ') // Replace punctuation with space
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/**
 * Helper to match and retrieve detailed lesson from the grounded Moroccan curriculum database.
 * Strictly avoids cross-confusion between distinct curriculum lessons (e.g. Capitalism vs Imperialism).
 */
export function getDetailedMoroccanLessonContent(lessonTitle: string): LessonDetailedContent | null {
  if (!lessonTitle) return null;
  const cleanTitle = lessonTitle.trim();

  // 1. Direct key lookup
  if (MOROCCAN_LESSONS_DATABASE[cleanTitle]) {
    return MOROCCAN_LESSONS_DATABASE[cleanTitle];
  }

  // 2. Normalized full string matching
  const normalizedInput = normalizeArabic(cleanTitle);
  for (const [key, val] of Object.entries(MOROCCAN_LESSONS_DATABASE)) {
    const normalizedKey = normalizeArabic(key);
    if (normalizedInput === normalizedKey) {
      return val;
    }
  }

  // 3. Containment match (with strict topic divergence guard)
  for (const [key, val] of Object.entries(MOROCCAN_LESSONS_DATABASE)) {
    const normalizedKey = normalizeArabic(key);
    if (normalizedInput.includes(normalizedKey) || (normalizedKey.includes(normalizedInput) && normalizedInput.length >= 10)) {
      const isInputCapitalism = normalizedInput.includes('ازدهار') || (normalizedInput.includes('راسمال') && !normalizedInput.includes('امبريال'));
      const isKeyImperialism = normalizedKey.includes('امبريال') && !normalizedKey.includes('ازدهار');
      if (isInputCapitalism && isKeyImperialism) continue;

      const isInputImperialism = normalizedInput.includes('امبريال');
      const isKeyCapitalism = normalizedKey.includes('ازدهار') && !normalizedKey.includes('امبريال');
      if (isInputImperialism && isKeyCapitalism) continue;

      return val;
    }
  }

  // 4. Keyword matching on thematic tokens (excluding temporal and generic grammatical words)
  const stopWords = new Set([
    'درس', 'موضوع', 'في', 'من', 'عن', 'على', 'الى', 'إلى', 'مع', 'بين', 'حول', 'ان', 'أن',
    'لا', 'ما', 'هو', 'هي', 'التي', 'الذي', 'خلال', 'اثناء', 'عبر', 'اثر', 'مطلع', 'اواخر',
    'القرن', 'قرن', '19م', '20م', '19', '20', 'التاسع', 'العاشر', 'عشر'
  ]);
  const keywords = normalizedInput
    .split(/\s+/)
    .filter(w => w.length >= 3 && !stopWords.has(w));

  if (keywords.length === 0) return null;

  let bestMatch: LessonDetailedContent | null = null;
  let maxMatches = 0;

  for (const [key, val] of Object.entries(MOROCCAN_LESSONS_DATABASE)) {
    const normalizedKey = normalizeArabic(key);
    let matches = 0;
    for (const kw of keywords) {
      if (normalizedKey.includes(kw)) matches++;
    }

    // Strict guard against cross-confusion between Lesson 1 (Capitalism) and Lesson 2 (Imperialism)
    const isSearchingCapitalism = keywords.some(k => k.includes('ازدهار') || (k.includes('راسمال') && !keywords.some(x => x.includes('امبريال'))));
    const isCandidateImperialism = normalizedKey.includes('امبريال') && !normalizedKey.includes('ازدهار');
    if (isSearchingCapitalism && isCandidateImperialism) {
      continue;
    }

    const isSearchingImperialism = keywords.some(k => k.includes('امبريال'));
    const isCandidateCapitalism = normalizedKey.includes('ازدهار') && !normalizedKey.includes('امبريال');
    if (isSearchingImperialism && isCandidateCapitalism) {
      continue;
    }

    if (matches > maxMatches && (matches >= 2 || (keywords.length === 1 && matches === 1))) {
      maxMatches = matches;
      bestMatch = val;
    }
  }

  return bestMatch;
}
