Object.assign(MOROCCAN_LESSONS_DATABASE, EXTENDED_MOROCCAN_LESSONS);

/**
 * Normalizes Arabic text for flexible matching (removes diacritics, unifies alifs, etc.)
 */
function normalizeArabic(text: string): string {
  return text
    .replace(/[\u064B-\u065F\u0670]/g, '') // Remove tashkeel / diacritics
    .replace(/[إأآٱ]/g, 'ا') // Normalize alif
    .replace(/ة/g, 'ه') // Normalize taa marbuta
    .replace(/ى/g, 'ي') // Normalize alif maqsoora
    .replace(/[^\u0600-\u06FFa-zA-Z0-9\s]/g, ' ') // Replace punctuation with space
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/**
 * Helper to match and retrieve detailed lesson from the grounded Moroccan curriculum database.
 */
export function getDetailedMoroccanLessonContent(lessonTitle: string): LessonDetailedContent | null {
  if (!lessonTitle) return null;
  const cleanTitle = lessonTitle.trim();

  // 1. Direct key lookup
  if (MOROCCAN_LESSONS_DATABASE[cleanTitle]) {
    return MOROCCAN_LESSONS_DATABASE[cleanTitle];
  }

  // 2. Normalized full string matching
  const normalizedInput = normalizeArabic(cleanTitle);
  for (const [key, val] of Object.entries(MOROCCAN_LESSONS_DATABASE)) {
    const normalizedKey = normalizeArabic(key);
    if (normalizedInput === normalizedKey || normalizedInput.includes(normalizedKey) || normalizedKey.includes(normalizedInput)) {
      return val;
    }
  }

  // 3. Keyword matching on normalized tokens
  const stopWords = new Set(['درس', 'موضوع', 'في', 'من', 'عن', 'على', 'الى', 'إلى', 'مع', 'بين', 'حول', 'ان', 'أن', 'لا', 'ما', 'هو', 'هي', 'التي', 'الذي', 'التي']);
  const keywords = normalizedInput
    .split(/\s+/)
    .filter(w => w.length >= 3 && !stopWords.has(w));

  let bestMatch: LessonDetailedContent | null = null;
  let maxMatches = 0;

  for (const [key, val] of Object.entries(MOROCCAN_LESSONS_DATABASE)) {
    const normalizedKey = normalizeArabic(key);
    let matches = 0;
    for (const kw of keywords) {
      if (normalizedKey.includes(kw)) matches++;
    }
    if (matches > maxMatches && (matches >= 2 || (keywords.length === 1 && matches === 1))) {
      maxMatches = matches;
      bestMatch = val;
    }
  }

  return bestMatch;
}
